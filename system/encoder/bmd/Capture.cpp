// isso eh problematico para mais um uma captura em paralelo (FIX)
static IDeckLinkInput*	g_deckLinkInput = NULL;

static unsigned long	g_frameCount = 0;

DeckLinkCaptureDelegate::DeckLinkCaptureDelegate() : m_refCount(1)
{
}

ULONG DeckLinkCaptureDelegate::AddRef(void)
{
	return __sync_add_and_fetch(&m_refCount, 1);
}

ULONG DeckLinkCaptureDelegate::Release(void)
{
	int32_t newRefValue = __sync_sub_and_fetch(&m_refCount, 1);
	if (newRefValue == 0)
	{
		delete this;
		return 0;
	}
	return newRefValue;
}

HRESULT DeckLinkCaptureDelegate::VideoInputFrameArrived(IDeckLinkVideoInputFrame* videoFrame, IDeckLinkAudioInputPacket* audioFrame)
{
	void*								frameBytes;
	void*								audioFrameBytes;

        // these types are all int64_t
        BMDTimeScale desiredTimeScale = 90000;
        BMDTimeValue hardwareTime;
        BMDTimeValue timeInFrame;
        BMDTimeValue ticksPerFrame;

        g_deckLinkInput->GetHardwareReferenceClock(desiredTimeScale, &hardwareTime, &timeInFrame, &ticksPerFrame);
        // tvltx_debug("HW time: %lld ticksPerFrame: %lld\n", hardwareTime, ticksPerFrame);

	// Handle Video Frame
	if (videoFrame)
	{
                videoFrame->GetBytes(&frameBytes);

		if (videoFrame->GetFlags() & bmdFrameHasNoInputSource)
		{
                    // tvltx_debug("No input signal detected! Frame received (#%lu)\n", g_frameCount);  

                    unsigned bars[8] = {
                        0xEA80EA80, 0xD292D210, 0xA910A9A5, 0x90229035,
                        0x6ADD6ACA, 0x51EF515A, 0x286D28EF, 0x10801080 };
                    int width  = videoFrame->GetWidth();
                    int height = videoFrame->GetHeight();
                    unsigned *p = (unsigned *)frameBytes;

                    for (int y = 0; y < height; y++) {
                        for (int x = 0; x < width; x += 2)
                            *p++ = bars[(x * 8) / width];
                    }
                }

                // TODO  - get video size only once in the beginning?
                for (int i = 0; i < nr_services; i++){
                    if (services[i].input_id == input_loc->input_id){
                        write_buffer(&services[i].buf_video_in, (uint8_t *)frameBytes, videoFrame->GetRowBytes() * videoFrame->GetHeight());
                    }
                }
                g_frameCount++;
        }
        else {
            tvltx_debug("NULL Video Frame\n");
        }

	// Handle Audio Frame
	if (audioFrame){
		audioFrame->GetBytes(&audioFrameBytes);
                int sample_count = audioFrame->GetSampleFrameCount();
/* write to circular buffer */
                for (int i = 0; i < nr_services; i++){
                    if (services[i].input_id == input_loc->input_id){
                        for (int j = 0; j < services[i].nr_audio_streams; j++){
                            write_buffer(&services[i].buf_audio_in[j], (uint8_t *)audioFrameBytes, sample_count * services[i].nr_channels[j] * 2); // 16 bits per sample
                        }
                    }
                }
	}
        else {
            tvltx_debug("NULL Audio Frame\n");
        }

	if (running == false)
	{
		g_do_exit = true;
		pthread_cond_signal(&g_sleepCond);
	}

	return S_OK;
}

HRESULT DeckLinkCaptureDelegate::VideoInputFormatChanged(BMDVideoInputFormatChangedEvents events, IDeckLinkDisplayMode *mode, BMDDetectedVideoInputFormatFlags formatFlags)
{
	// This only gets called if bmdVideoInputEnableFormatDetection was set
	// when enabling video input
	HRESULT	result;
	char*	displayModeName = NULL;
	BMDPixelFormat	pixelFormat = bmdFormat10BitYUV;

	if (formatFlags & bmdDetectedVideoInputRGB444)
		pixelFormat = bmdFormat10BitRGB;

	mode->GetName((const char**)&displayModeName);
	printf("Video format changed to %s %s\n", displayModeName, formatFlags & bmdDetectedVideoInputRGB444 ? "RGB" : "YUV");

	if (displayModeName)
		free(displayModeName);

	if (g_deckLinkInput)
	{
		g_deckLinkInput->StopStreams();

		result = g_deckLinkInput->EnableVideoInput(mode->GetDisplayMode(), pixelFormat, 0 /* g_config.m_inputFlags */);
		if (result != S_OK)
		{
			fprintf(stderr, "Failed to switch video mode\n");
			goto bail;
		}

		g_deckLinkInput->StartStreams();
	}

bail:
	return S_OK;
}

void *input_bmd_thread(void *input_v)
{
    input_loc = (input_config *) input_v;
    HRESULT							result;
    int								exitStatus = 1;
    int								idx;

    IDeckLinkIterator*				deckLinkIterator = NULL;
    IDeckLink*						deckLink = NULL;

    IDeckLinkAttributes*			deckLinkAttributes = NULL;
    bool							formatDetectionSupported;

    IDeckLinkDisplayModeIterator*	displayModeIterator = NULL;
    IDeckLinkDisplayMode*			displayMode = NULL;
    char*							displayModeName = NULL;
    BMDDisplayModeSupport			displayModeSupported;
    
    IDeckLinkConfiguration *deckLinkConfiguration;
    
    DeckLinkCaptureDelegate*		delegate = NULL;
    
    pthread_mutex_init(&g_sleepMutex, NULL);
    pthread_cond_init(&g_sleepCond, NULL);
    
    // Get the DeckLink device
    deckLinkIterator = CreateDeckLinkIteratorInstance();
    if (!deckLinkIterator)
    {
        fprintf(stderr, "This application requires the DeckLink drivers installed.\n");
        goto bail;
    }
    
    idx = input_loc->card_number;
    
    while ((result = deckLinkIterator->Next(&deckLink)) == S_OK)
    {
        if (idx == 0)
                break;
        --idx;
        deckLink->Release();
    }

    if (result != S_OK || deckLink == NULL)
    {
        fprintf(stderr, "Unable to get DeckLink device %u\n", input_loc->card_number);
        goto bail;
    }
    
    // Get the input (capture) interface of the DeckLink device
	result = deckLink->QueryInterface(IID_IDeckLinkInput, (void**)&g_deckLinkInput);
	if (result != S_OK)
		goto bail;

        result = deckLink->QueryInterface(IID_IDeckLinkConfiguration,
                                          (void **)&deckLinkConfiguration);
        if (result != S_OK) {
            fprintf(
                stderr,
                "Could not obtain the IDeckLinkConfiguration interface - result = %08x\n",
                result);
            goto bail;
        }

        result = S_OK;
        result = deckLinkConfiguration->SetInt(bmdDeckLinkConfigAudioInputConnection,bmdAudioConnectionEmbedded);

        if (result != S_OK) {
            fprintf(stderr, "Failed to set audio input - result = %08x\n", result);
            goto bail;
        }

        result = S_OK;
        switch (input_loc->input_type) {
        case INPUT_TYPE_COMPOSITE:
            result = deckLinkConfiguration->SetInt(bmdDeckLinkConfigVideoInputConnection, bmdVideoConnectionComposite);
            break;
        case INPUT_TYPE_COMPONENT:
            result = deckLinkConfiguration->SetInt(bmdDeckLinkConfigVideoInputConnection, bmdVideoConnectionComponent);
            break;
        case INPUT_TYPE_HDMI:
            result = deckLinkConfiguration->SetInt(bmdDeckLinkConfigVideoInputConnection, bmdVideoConnectionHDMI);
            break;
        case INPUT_TYPE_SDI:
            result = deckLinkConfiguration->SetInt(bmdDeckLinkConfigVideoInputConnection, bmdVideoConnectionSDI);
            break;
        case INPUT_TYPE_OPTICALSDI:
            result = deckLinkConfiguration->SetInt(bmdDeckLinkConfigVideoInputConnection, bmdVideoConnectionOpticalSDI);
            break;
        case INPUT_TYPE_SVIDEO:
            result = deckLinkConfiguration->SetInt(bmdDeckLinkConfigVideoInputConnection, bmdVideoConnectionSVideo);
            break;
        default:
            tvltx_info("No Mode Set!\n");
            // do not change it
            break;
        }
        if (result != S_OK) {
            fprintf(stderr, "Failed to set video input - result %08x\n", result);
            goto bail;
        }
        
        
	// Configure the capture callback
	delegate = new DeckLinkCaptureDelegate();
	g_deckLinkInput->SetCallback(delegate);

        int display_mode;
        switch(input_loc->video_input_mode){
        case VIDEO_MODE_480_P_2997:
            display_mode = bmdModeNTSCp;
            break;
        case VIDEO_MODE_576_P_25:
            display_mode = bmdModePALp;
            break;
        case VIDEO_MODE_480_I_5994:
            display_mode = bmdModeNTSC;
            break;
        case VIDEO_MODE_576_I_50:
            display_mode = bmdModePAL;
            break;
        case VIDEO_MODE_1080_P_25:
            display_mode = bmdModeHD1080p25;
            break;
        case VIDEO_MODE_1080_P_2997:
            display_mode = bmdModeHD1080p2997;
            break;
        case VIDEO_MODE_1080_P_30:
            display_mode = bmdModeHD1080p30;
            break;
        case VIDEO_MODE_1080_I_50:
            display_mode = bmdModeHD1080i50;
            break;
        case VIDEO_MODE_1080_I_5994:
            display_mode = bmdModeHD1080i5994;
            break;
        case VIDEO_MODE_1080_I_60:
            display_mode = bmdModeHD1080i6000;
            break;
        case VIDEO_MODE_1080_P_50:
            display_mode = bmdModeHD1080p50;
            break;
        case VIDEO_MODE_1080_P_5994:
            display_mode = bmdModeHD1080p5994;
            break;
        case VIDEO_MODE_1080_P_60:
            display_mode = bmdModeHD1080p6000;
            break;
        case VIDEO_MODE_720_P_50:
            display_mode = bmdModeHD720p50;
            break;
        case VIDEO_MODE_720_P_5994:
            display_mode = bmdModeHD720p5994;
            break;
        case VIDEO_MODE_720_P_60:
            display_mode = bmdModeHD720p60;
            break;
        default:
            tvltx_info("No mode selected or mode not supported\n");
        }

        // get mode info
        result = g_deckLinkInput->GetDisplayModeIterator(&displayModeIterator);
        if (result != S_OK) {
            tvltx_info("Could not obtain the video output display mode iterator - result = %08x\n", result);
            goto bail;
        }

        while (displayModeIterator->Next(&displayMode) == S_OK) {
            if ( display_mode == displayMode->GetDisplayMode() ) {
                break;
            }
            displayMode->Release();
        }

        if (displayMode) {
            BMDTimeValue frameRateDuration, frameRateScale;
            displayMode->GetFrameRate(&frameRateDuration, &frameRateScale);
            tvltx_info("Num: %ld   Den: %ld\n", frameRateDuration, frameRateScale);
        }

	// Block main thread until signal occurs
	while (!g_do_exit)
	{
		// Start capturing
		result = g_deckLinkInput->EnableVideoInput(display_mode, bmdFormat8BitYUV, 0);
		if (result != S_OK)
		{
                    tvltx_info("Failed to enable video input. Is another application using the card?\n");
                    goto bail;
		}

                // TODO: get all channels
		result = g_deckLinkInput->EnableAudioInput(bmdAudioSampleRate48kHz, 16, input_loc->audio_input_channel_nr); 
		if (result != S_OK){
                    tvltx_info("Failed to enable audio input\n");
                    goto bail;
                }

		result = g_deckLinkInput->StartStreams();
		if (result != S_OK)
			goto bail;

		// All Okay.
		exitStatus = 0;

		pthread_mutex_lock(&g_sleepMutex);
		pthread_cond_wait(&g_sleepCond, &g_sleepMutex);
		pthread_mutex_unlock(&g_sleepMutex);

		fprintf(stderr, "Stopping Capture\n");
		g_deckLinkInput->StopStreams();
		g_deckLinkInput->DisableAudioInput();
		g_deckLinkInput->DisableVideoInput();
	}

bail:
	if (displayModeName != NULL)
		free(displayModeName);

	if (displayMode != NULL)
		displayMode->Release();

	if (displayModeIterator != NULL)
		displayModeIterator->Release();

	if (delegate != NULL)
		delegate->Release();

	if (g_deckLinkInput != NULL)
	{
		g_deckLinkInput->Release();
		g_deckLinkInput = NULL;
	}

	if (deckLinkAttributes != NULL)
		deckLinkAttributes->Release();

	if (deckLinkConfiguration != NULL)
		deckLinkConfiguration->Release();

	if (deckLink != NULL)
		deckLink->Release();

	if (deckLinkIterator != NULL)
		deckLinkIterator->Release();

	return EXIT_SUCCESS;
}

